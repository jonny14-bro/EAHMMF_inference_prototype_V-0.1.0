#!/usr/bin/env python3
"""Generates unicode_tables.h: sorted [lo,hi] ranges for \\p{L} and \\p{N}."""
import unicodedata


def ranges(pred):
    res, s = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and s is None:
            s = cp
        elif not ok and s is not None:
            res.append((s, cp - 1))
            s = None
    if s is not None:
        res.append((s, 0x10FFFF))
    return res


def emit(name, rs):
    body = ",".join(f"{{0x{a:X},0x{b:X}}}" for a, b in rs)
    return (f"static const uint32_t {name}[][2]={{{body}}};\n"
            f"static const size_t {name}_N={len(rs)};\n")


L = ranges(lambda c: unicodedata.category(chr(c)).startswith("L"))
N = ranges(lambda c: unicodedata.category(chr(c)).startswith("N"))
with open("unicode_tables.h", "w") as f:
    f.write(f"// generated by gen_unicode.py (Unicode {unicodedata.unidata_version})\n")
    f.write("#pragma once\n#include <cstdint>\n#include <cstddef>\n")
    f.write(emit("UNI_L", L))
    f.write(emit("UNI_N", N))
print("L ranges:", len(L), "N ranges:", len(N))
